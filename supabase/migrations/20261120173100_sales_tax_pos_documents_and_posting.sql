ALTER TABLE public.invoices ADD COLUMN sales_tax_snapshot jsonb;
CREATE FUNCTION public.neo_invoice_sales_tax_snapshot_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
BEGIN
  IF TG_OP='UPDATE' AND OLD.sales_tax_snapshot IS NOT NULL
    AND NEW.sales_tax_snapshot IS DISTINCT FROM OLD.sales_tax_snapshot THEN
    RAISE EXCEPTION 'Saved invoice tax evidence is immutable';
  END IF;
  IF current_user IN ('authenticated','anon') AND NEW.sales_tax_snapshot IS NOT NULL THEN
    IF TG_OP='INSERT' OR NEW.sales_tax_snapshot IS DISTINCT FROM OLD.sales_tax_snapshot THEN
      RAISE EXCEPTION 'Invoice tax evidence is generated by the source transaction';
    END IF;
  END IF;
  RETURN NEW;
END
$$;
CREATE TRIGGER neo_invoice_sales_tax_snapshot_guard BEFORE INSERT OR UPDATE OF sales_tax_snapshot ON public.invoices
  FOR EACH ROW EXECUTE FUNCTION public.neo_invoice_sales_tax_snapshot_guard();

-- Allocate a bill-level adjustment across persisted components in cents. A
-- mixed basket keeps any legacy tax in the existing liability account.
CREATE FUNCTION public.neo_sales_tax_allocate_parts(_parts jsonb,_basis numeric,_after_discount numeric)
RETURNS TABLE(code text,label text,account_code text,included boolean,amount numeric)
LANGUAGE sql IMMUTABLE SET search_path=pg_catalog AS $$
  WITH grouped AS (
    SELECT p->>'code' code,p->>'name' label,p->>'account_code' account_code,
      (p->>'inclusive')::boolean included,sum((p->>'amount')::numeric) raw
    FROM jsonb_array_elements(_parts) AS source(p) GROUP BY 1,2,3,4
  ), running AS (
    SELECT g.*,sum(raw) OVER (ORDER BY code,label,account_code,included) cumulative FROM grouped g
  )
  SELECT code,label,account_code,included,
    CASE WHEN _basis>0 THEN round(cumulative*least(greatest(_after_discount,0),_basis)/_basis,2)
      -round((cumulative-raw)*least(greatest(_after_discount,0),_basis)/_basis,2) ELSE 0 END
  FROM running
$$;

CREATE FUNCTION public.neo_pos_saved_sales_taxes(_order uuid, _basis numeric, _after_discount numeric)
RETURNS TABLE(code text, label text, account_code text, included boolean, amount numeric)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
  WITH source AS (
    SELECT r.part||jsonb_build_object('account_code',
      CASE WHEN coalesce((r.part->>'legacy')::boolean,false) THEN '2040' ELSE a.code END) part
    FROM public.pos_order_items i
    CROSS JOIN LATERAL jsonb_array_elements(
      CASE WHEN i.sales_tax_snapshot IS NOT NULL THEN
        i.sales_tax_snapshot->'taxes'
      WHEN i.tax_amount<>0 THEN jsonb_build_array(jsonb_build_object(
        'code','LEGACY','name','Tax','amount',i.tax_amount,'inclusive',true,'legacy',true))
      ELSE '[]'::jsonb END
    ) r(part)
    LEFT JOIN public.chart_of_accounts a ON a.organization_id=i.organization_id
      AND a.id=(i.sales_tax_snapshot->'accounts'->>(r.part->>'code'))::uuid
    WHERE i.order_id=_order AND i.status NOT IN ('cancelled','voided')
  )
  SELECT t.* FROM public.neo_sales_tax_allocate_parts((SELECT jsonb_agg(part) FROM source),_basis,_after_discount) t
$$;

CREATE FUNCTION public.neo_delivery_sales_tax_breakdown(_lines jsonb,_basis numeric,_after_discount numeric)
RETURNS jsonb LANGUAGE sql IMMUTABLE SET search_path=pg_catalog AS $$
  WITH components AS (
    SELECT r.part FROM jsonb_array_elements(_lines) AS quote(line)
    CROSS JOIN LATERAL jsonb_array_elements(CASE WHEN jsonb_typeof(line->'tax_parts')='array'
      THEN line->'tax_parts' ELSE jsonb_build_array(jsonb_build_object('code','LEGACY','name','Tax',
        'inclusive',true,'amount',round((line->>'line_total')::numeric*(line->>'tax_rate')::numeric/
          (100+(line->>'tax_rate')::numeric),2))) END) AS r(part)
  )
  SELECT coalesce(jsonb_agg(jsonb_build_object('label',t.label||
    CASE WHEN t.code=t.label OR t.code='LEGACY' THEN '' ELSE ' ('||t.code||')' END||
    CASE WHEN t.included THEN ' · Included' ELSE ' · Added' END,'amount',t.amount) ORDER BY t.code,t.label,t.included),'[]')
  FROM public.neo_sales_tax_allocate_parts((SELECT jsonb_agg(part) FROM components),_basis,_after_discount) t
  WHERE t.amount<>0 OR t.code<>'LEGACY'
$$;

CREATE FUNCTION public.neo_pos_sales_tax_post_lines(_order uuid, _basis numeric, _after_discount numeric)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE result jsonb;
BEGIN
  IF EXISTS(SELECT 1 FROM public.neo_pos_saved_sales_taxes(_order,_basis,_after_discount) t
      WHERE t.amount<>0 AND t.account_code IS NULL) THEN
    RAISE EXCEPTION 'The saved sales tax liability account is unavailable';
  END IF;
  SELECT coalesce(jsonb_agg(jsonb_build_object('code',t.account_code,'credit',t.amount,
    'description',t.label||' ('||t.code||')') ORDER BY t.code,t.account_code),'[]')
  INTO result FROM public.neo_pos_saved_sales_taxes(_order,_basis,_after_discount) t WHERE t.amount<>0;
  RETURN result;
END
$$;

CREATE FUNCTION public.neo_document_replace_tax_total(_totals jsonb, tax_rows jsonb, net numeric DEFAULT NULL)
RETURNS jsonb LANGUAGE sql IMMUTABLE SET search_path = pg_catalog AS $$
  SELECT coalesce(jsonb_agg(part ORDER BY ordinal),'[]') FROM (
    SELECT e.part,e.ordinal*10000 ordinal FROM jsonb_array_elements(_totals) WITH ORDINALITY e(part,ordinal)
    WHERE lower(e.part->>'label') <> 'tax'
    UNION ALL
    SELECT jsonb_build_object('label','Net before tax','amount',net),e.ordinal*10000
    FROM jsonb_array_elements(_totals) WITH ORDINALITY e(part,ordinal)
    WHERE lower(e.part->>'label')='tax' AND net IS NOT NULL
    UNION ALL
    SELECT jsonb_build_object('label',t.part->>'label','amount',(t.part->>'amount')::numeric),
      e.ordinal*10000+t.ordinal FROM jsonb_array_elements(_totals) WITH ORDINALITY e(part,ordinal)
    CROSS JOIN jsonb_array_elements(tax_rows) WITH ORDINALITY t(part,ordinal)
    WHERE lower(e.part->>'label')='tax'
  ) rendered
$$;

CREATE FUNCTION public.neo_pos_sales_tax_receipt(_order uuid, _totals jsonb)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE sale public.pos_orders; amount numeric; tax_rows jsonb;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.pos_order_items WHERE order_id=_order AND sales_tax_snapshot IS NOT NULL
    AND status NOT IN ('cancelled','voided')) THEN RETURN _totals; END IF;
  SELECT * INTO STRICT sale FROM public.pos_orders WHERE id=_order;
  SELECT coalesce(sum(t.amount),0),coalesce(jsonb_agg(jsonb_build_object(
    'label',t.label||CASE WHEN t.code='LEGACY' OR t.code=t.label THEN '' ELSE ' ('||t.code||')' END||
      CASE WHEN t.included THEN ' · Included' ELSE ' · Added' END,'amount',t.amount)
    ORDER BY t.code,t.label,t.included),'[]')
  INTO amount,tax_rows FROM (
    SELECT x.code,x.label,x.included,sum(x.amount) amount
    FROM public.neo_pos_saved_sales_taxes(_order,sale.subtotal,sale.subtotal-sale.discount_total) x
    GROUP BY 1,2,3
  ) t;
  RETURN public.neo_document_replace_tax_total(_totals,tax_rows,greatest(sale.subtotal-sale.discount_total,0)-amount);
END
$$;

-- Amend the installed routines in place. Exact anchors leave existing source
-- ownership, payment checks and function grants in place.
